#!/usr/bin/env node

/**
 * @shavin/mcp — Model Context Protocol Asset Bundler
 * Copies tokens.json, components.json, AGENTS.md, skills/, and commands/ into
 * packages/mcp-server/assets/ with Shavin TrueColor terminal styling,
 * animated loaders, and structured cards.
 */

import { existsSync, readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { resolve, join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { c, g, fmt, printBanner, printCard, printStage, formatDuration, startTaskSpinner } from "../../scripts/lib/term-ui.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const ROOT = resolve(__dirname, "..", "..");
const ASSETS_DIR = resolve(__dirname, "assets");

function copyFile(src, dst) {
  if (existsSync(src)) {
    mkdirSync(dirname(dst), { recursive: true });
    writeFileSync(dst, readFileSync(src));
  }
}

function copyDir(src, dst) {
  if (!existsSync(src)) return;
  mkdirSync(dst, { recursive: true });
  for (const entry of readdirSync(src)) {
    const srcPath = join(src, entry);
    const dstPath = join(dst, entry);
    if (statSync(srcPath).isDirectory()) {
      copyDir(srcPath, dstPath);
    } else {
      writeFileSync(dstPath, readFileSync(srcPath));
    }
  }
}

async function main() {
  process.stdout.write("\n");
  printBanner("@shavin/mcp", "Knowledge Asset Bundler");

  const startTime = Date.now();

  printStage(1, "Asset Assembly & Staging", "Bundle standalone knowledge assets into @shavin/mcp/assets/");

  // 1. Tokens & Components
  const spinner1 = startTaskSpinner({ prefix: "[1/4]", name: "Design Tokens & Manifest", desc: "Stage tokens.json & components.json" });
  copyFile(resolve(ROOT, "tokens.json"), resolve(ASSETS_DIR, "tokens.json"));
  copyFile(resolve(ROOT, "components.json"), resolve(ASSETS_DIR, "components.json"));
  copyFile(resolve(ROOT, "packages", "ui", "tokens.json"), resolve(ASSETS_DIR, "tokens.json"));
  copyFile(resolve(ROOT, "packages", "ui", "components.json"), resolve(ASSETS_DIR, "components.json"));
  spinner1.succeed();

  // 2. AGENTS.md Constitution
  const spinner2 = startTaskSpinner({ prefix: "[2/4]", name: "Agent Constitution", desc: "Stage AGENTS.md ruleset" });
  // The consumer rules generated by scripts/gen-agents.mjs, never the repo's own AGENTS.md.
  copyFile(resolve(ROOT, "packages", "skills", "AGENTS.md"), resolve(ASSETS_DIR, "AGENTS.md"));
  spinner2.succeed();

  // 3. Skills Library
  const spinner3 = startTaskSpinner({ prefix: "[3/4]", name: "Agent Skills Library", desc: "Stage skills directory" });
  const skillsSrc = existsSync(resolve(ROOT, "packages", "skills", "skills"))
    ? resolve(ROOT, "packages", "skills", "skills")
    : resolve(ROOT, ".agents", "skills");
  copyDir(skillsSrc, resolve(ASSETS_DIR, "skills"));
  spinner3.succeed();

  // 4. Slash Commands
  const spinner4 = startTaskSpinner({ prefix: "[4/4]", name: "Agent Slash Commands", desc: "Stage commands directory" });
  const commandsSrc = existsSync(resolve(ROOT, "packages", "skills", "commands"))
    ? resolve(ROOT, "packages", "skills", "commands")
    : resolve(ROOT, ".agents", "commands");
  copyDir(commandsSrc, resolve(ASSETS_DIR, "commands"));
  spinner4.succeed();

  const totalTime = Date.now() - startTime;

  printCard({
    title: `${c.brand}${g.brand} @shavin/mcp Build Complete${c.reset}`,
    items: [
      { label: "Assets Staged:", value: `${c.bold}${c.fg}tokens, components, AGENTS.md, skills, commands${c.reset}` },
      { label: "Output Location:", value: `${c.fg}packages/mcp-server/assets/${c.reset}` },
      { label: "Execution Mode:", value: `${c.fgSubtle}Self-contained standalone MCP package${c.reset}` },
      { label: "Total Duration:", value: `${c.bold}${c.fg}${formatDuration(totalTime)}${c.reset}` },
      { label: "Pipeline Status:", value: `${fmt.pass("SUCCESS")} ${fmt.badge("READY", c.success)}` },
    ],
    footer: `${c.fgSubtle}All knowledge assets bundled cleanly into @shavin/mcp distribution.${c.reset}`,
  });
}

main().catch((err) => {
  console.error(`\n  ${c.error}${g.stepFail} Build failed:${c.reset} ${err.message}`);
  process.exit(1);
});
