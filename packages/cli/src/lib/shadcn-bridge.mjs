/**
 * Theme bridge for projects that already use shadcn/ui (Tailwind 4): maps shadcn's CSS variables to Shavin's
 * tokens, so changing the Shavin brand (ThemeProvider brandColor, brand-tokens.css) restyles shadcn components
 * too, and light/dark follow Shavin's `.dark` class.
 *
 * Shavin's colour tokens are space-separated RGB triplets, so every value is wrapped in rgb(). Selectors are
 * `html:root` / `html.dark` (one element more specific than shadcn's `:root` / `.dark`), so this wins whichever
 * order the stylesheet loads in. Tailwind 3 shadcn uses hsl(var(--x)) triplets and is not bridged.
 */
export const SHADCN_BRIDGE_FILE = "shavin-shadcn-bridge.css";

export const SHADCN_BRIDGE_CSS = `/* Generated by \`shavin init\`: maps shadcn/ui variables to Shavin tokens.
   Change the brand once (ThemeProvider brandColor or brand-tokens.css) and shadcn components follow. */
html:root,
html.dark {
  --background: rgb(var(--bg-canvas));
  --foreground: rgb(var(--fg));
  --card: rgb(var(--bg-surface));
  --card-foreground: rgb(var(--fg));
  --popover: rgb(var(--bg-elevated));
  --popover-foreground: rgb(var(--fg));
  --primary: rgb(var(--brand-solid));
  --primary-foreground: rgb(var(--brand-fg));
  --secondary: rgb(var(--bg-surface-hover));
  --secondary-foreground: rgb(var(--fg));
  --muted: rgb(var(--bg-surface-hover));
  --muted-foreground: rgb(var(--fg-subtle));
  --accent: rgb(var(--bg-surface-hover));
  --accent-foreground: rgb(var(--fg));
  --destructive: rgb(var(--danger));
  --destructive-foreground: rgb(var(--danger-fg));
  --border: rgb(var(--hairline));
  --input: rgb(var(--hairline-strong));
  --ring: rgb(var(--brand));
  --radius: var(--radius-lg);
}
`;

/** The variables the bridge sets (used by doctor and tests). */
export const SHADCN_BRIDGE_VARS = [...SHADCN_BRIDGE_CSS.matchAll(/^\s+(--[\w-]+):/gm)].map((m) => m[1]);
