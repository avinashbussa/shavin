function parseVariants(src) {
  // A single file may contain multiple cva() calls (e.g. Typography.tsx
  // exports headingVariants and textVariants). We walk every "variants: {"
  // occurrence, extract the balanced-brace block, and merge all axes.
  // The key fix vs the old regex: option keys are only matched when followed
  // by a quoted value string, so Tailwind pseudo-class fragments like
  // "hover:" or "focus:" inside class values are NOT captured as keys.
  const merged = {};

  const variantsRegex = /variants\s*:\s*\{/g;
  let vm;
  while ((vm = variantsRegex.exec(src)) !== null) {
    // Walk braces to find the end of the variants object
    let depth = 1;
    let i = vm.index + vm[0].length;
    const start = i;
    while (i < src.length && depth > 0) {
      if (src[i] === '{') depth++;
      else if (src[i] === '}') depth--;
      i++;
    }
    const block = src.slice(start, i - 1);

    // Parse each axis within this variants block
    let pos = 0;
    while (pos < block.length) {
      const keyMatch = block.slice(pos).match(/^[\s\n,]*([A-Za-z0-9_$]+)\s*:\s*\{/);
      if (!keyMatch) {
        pos++;
        continue;
      }
      const axis = keyMatch[1];
      pos += keyMatch[0].length;
      // Walk braces for this axis block
      depth = 1;
      const axisStart = pos;
      while (pos < block.length && depth > 0) {
        if (block[pos] === '{') depth++;
        else if (block[pos] === '}') depth--;
        pos++;
      }
      const axisBlock = block.slice(axisStart, pos - 1);

      // Extract option keys — ONLY match keys that are followed by a quoted
      // value string. The `(?:^|[\s,])` anchor ensures we don't capture
      // fragments inside quoted Tailwind class values like "hover:border".
      const opts = [];
      // A value may also be a SCREAMING_CASE constant (Heading's fluid sizes); Tailwind
      // classes are lowercase, so this never matches inside a class string.
      const optRe = /(?:^|[\s,])(?:"([^"]+)"|'([^']+)'|([A-Za-z0-9_$]+))\s*:\s*(?:["'`]|[A-Z_][A-Z0-9_]*\s*[,}\n])/gm;
      let om;
      while ((om = optRe.exec(axisBlock)) !== null) {
        const val = om[1] || om[2] || om[3];
        if (val && !opts.includes(val)) opts.push(val);
      }
      if (opts.length > 0) {
        if (!merged[axis]) {
          merged[axis] = [...opts];
        } else {
          for (const o of opts) {
            if (!merged[axis].includes(o)) merged[axis].push(o);
          }
        }
      }
    }
  }

  return merged;
}

function parseDefaults(src) {
  // A file may contain multiple defaultVariants blocks (one per cva() call).
  // Merge them — later values win (e.g. Text's defaults override Heading's
  // when both are in Typography.tsx).
  const defaults = {};
  const defaultsRegex = /defaultVariants\s*:\s*\{([^}]*)\}/g;
  let dm;
  while ((dm = defaultsRegex.exec(src)) !== null) {
    const block = dm[1];
    const kvRe = /([A-Za-z0-9_$]+)\s*:\s*(?:"([^"]+)"|'([^']+)'|([A-Za-z0-9_$]+))/g;
    let km;
    while ((km = kvRe.exec(block)) !== null) {
      defaults[km[1]] = km[2] || km[3] || km[4];
    }
  }
  return defaults;
}
/** Every `const x = cva(...)` in a file, with its own variants and defaults. */
function cvaBlocks(src) {
  const out = [];
  for (const m of src.matchAll(/(?:const|let)\s+([A-Za-z_$][\w$]*)\s*=\s*cva\s*\(/g)) {
    let depth = 1;
    let i = m.index + m[0].length;
    while (i < src.length && depth > 0) {
      if (src[i] === "(") depth++;
      else if (src[i] === ")") depth--;
      i++;
    }
    const seg = src.slice(m.index, i);
    out.push({ name: m[1], variants: parseVariants(seg), defaults: parseDefaults(seg) });
  }
  // Aliases: `const panelVariants = modalPanelVariants;`
  for (const m of src.matchAll(/(?:const|let)\s+([A-Za-z_$][\w$]*)\s*=\s*([A-Za-z_$][\w$]*)\s*;/g)) {
    const target = out.find((b) => b.name === m[2]);
    if (target) out.push({ ...target, name: m[1] });
  }
  return out;
}

/**
 * The cva variants that belong to one component: those its props extend
 * (`VariantProps<typeof xVariants>` in `interface NameProps`, a `type NameProps`
 * or the function signature). A file's other cva configs (e.g. Heading's scale
 * in a file that also exports Kbd) are not that component's props.
 * The file's primary component keeps every variant in the file when no link is
 * found, as before.
 */
function variantsFor(src, name, blocks, isPrimary) {
  const sources = [];
  const header = src.match(new RegExp(`interface\\s+${name}Props\\b[^{]*|type\\s+${name}Props\\s*=[^;{]*`));
  if (header) sources.push(header[0]);
  const fn = src.match(new RegExp(`function\\s+${name}\\s*(?:<[^>]*>)?\\s*\\(`));
  if (fn) {
    const rest = src.slice(fn.index, fn.index + 2000);
    const end = rest.search(/\)\s*(?::[^{=]*)?(?:\{|=>)/);
    sources.push(end > 0 ? rest.slice(0, end) : rest);
  }
  const used = new Set();
  for (const text of sources) for (const m of text.matchAll(/VariantProps<\s*typeof\s+([A-Za-z_$][\w$]*)\s*>/g)) used.add(m[1]);
  const picked = used.size ? blocks.filter((b) => used.has(b.name)) : isPrimary ? blocks : [];
  const variants = {};
  const defaults = {};
  for (const b of picked) {
    for (const [axis, opts] of Object.entries(b.variants)) variants[axis] = [...new Set([...(variants[axis] ?? []), ...opts])];
    Object.assign(defaults, b.defaults);
  }
  return { variants, defaults };
}

function parseProps(src, componentName) {
  const interfaceRe = new RegExp(`export\\s+interface\\s+${componentName}Props[^{]*\\{([\\s\\S]*?)\\n\\}`);
  const match = src.match(interfaceRe);
  const body = match ? match[1] : "";
  const props = [];

  // Resolve BgMediaProps usage — inject bg* media props into the manifest so
  // PropsTable and AI agents see the full prop surface. BgMediaProps is a
  // shared interface in media-overlays.tsx; we inline its fields here to avoid
  // cross-file interface resolution complexity. We check if this specific
  // component uses BgMediaProps — either via `extends ... BgMediaProps` in a
  // named interface, or via an inline type intersection in the function
  // signature: `function Card(...): HTMLAttributes & ... & BgMediaProps`.
  const usesBgMedia =
    // Named interface: export interface FlexProps extends ... BgMediaProps
    new RegExp(`export\\s+interface\\s+${componentName}Props\\s+extends[^{]*BgMediaProps`).test(src) ||
    // Inline type in function signature: function Card(...): ... & BgMediaProps ...
    new RegExp(`function\\s+${componentName}[\\s\\S]{0,500}?BgMediaProps`).test(src);
  if (usesBgMedia) {
    props.push(
      { name: "bgVideo", type: "string", required: false, doc: "Background video URL (mp4, webm, etc.). Renders an autoPlay/loop/muted <video> element behind children." },
      { name: "bgImage", type: "string", required: false, doc: "Background image URL. Renders an <img> with object-cover (default) or object-contain." },
      { name: "bgSize", type: '"cover" | "contain"', required: false, doc: "Background media fit. \"cover\" fills the container (default), \"contain\" fits within.", default: "cover" },
      { name: "bgOverlays", type: "string", required: false, doc: "Comma-separated shorthand for overlay layers. Supports presets (\"dark-50\"), solid colors (#hex or (token)), gradients (linear/radial), and fx backdrops (\"fx:dither-waves\", \"fx:fluid-silk(speed=1.2)\"; needs @shavin/fx registered, else falls back to mesh). JSON array of OverlayLayer[] as fallback for advanced cases. Layers composite top-to-bottom." },
      { name: "bgVideoPaused", type: "boolean", required: false, doc: "When true, pauses the background video (renders a static poster frame instead of autoplay).", default: "false" },
    );
  }

  // ResizableProps (resizable, minWidth, ...) are shared by Box, Flex and Card through
  // withResizable. Read them from their one declaration so the manifest never drifts.
  const usesResizable =
    componentName !== "Resizable" &&
    (new RegExp(`export\\s+interface\\s+${componentName}Props\\s+extends[^{]*ResizableProps`).test(src) ||
      new RegExp(`function\\s+${componentName}[\\s\\S]{0,800}?ResizableProps`).test(src));
  if (usesResizable && existsSync(RESIZABLE_SRC)) {
    props.push(...parseProps(readFileSync(RESIZABLE_SRC, "utf8"), "Resizable"));
  }

  if (!match) return props;
  const propBlockRe = /(?:\/\*\*([\s\S]*?)\*\/\s*)?([A-Za-z0-9_$]+)(\?)?:\s*([^;\n]+);?/g;
  let m;
  while ((m = propBlockRe.exec(body))) {
    const rawComment = m[1] ? m[1].replace(/^\s*\*\s?/gm, "").replace(/\n/g, " ").replace(/\s+/g, " ").trim() : "";
    const name = m[2];
    const optional = Boolean(m[3]);
    const rawType = m[4].trim();
    let defaultVal = undefined;
    const defMatch = rawComment.match(/@default\s+["']?([^"'\s]+)["']?/i) || rawComment.match(/Default\s+["']?(-?\d+(?:\.\d+)?|[^"'.\s]+)["']?/i);
    if (defMatch) {
      defaultVal = defMatch[1];
    }
    props.push({
      name,
      type: rawType,
      required: !optional,
      doc: rawComment,
      ...(defaultVal ? { default: defaultVal } : {}),
    });
  }
  return props;
}

function exportsOf(src) {
  const names = new Set();
  for (const m of src.matchAll(/export\s+(?:async\s+)?(?:function|const|class)\s+([A-Za-z_$][\w$]*)/g)) names.add(m[1]);
  for (const m of src.matchAll(/export\s+\{([^}]*)\}/g)) {
    for (const part of m[1].split(",")) {
      const id = part.trim().split(/\s+as\s+/).pop().trim();
      if (id) names.add(id);
    }
  }
  return [...names].sort();
}

function compressText(text) {
  if (!text) return "";
  return text
    .replace(/\b(a|an|the|is used for|provides|supports|allows|whether)\b/gi, "")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Load a co-located {Name}.doc.ts by compiling it with TypeScript and running
 * it, so examples, best practices and descriptions arrive exactly as written.
 * (A regex reader used to cut example code at the first `" }` and skipped
 * template-literal and quoted-key examples, so agents got broken snippets.)
 * Doc files may only `import type`, which compiles away.
 */
function evaluateDocFile(path) {
  const js = ts.transpileModule(readFileSync(path, "utf8"), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
    fileName: path,
  }).outputText;
  const module = { exports: {} };
  const require = (id) => {
    throw new Error(`${relative(ROOT, path)}: doc files cannot import "${id}" at runtime (use import type)`);
  };
  vm.runInNewContext(js, { module, exports: module.exports, require }, { filename: path });
  return module.exports.docs ?? module.exports.doc ?? null;
}

function loadCoLocatedDoc(fileDir, primaryName) {
  const docPathTS = join(fileDir, `${primaryName}.doc.ts`);
  const docPathJS = join(fileDir, `${primaryName}.doc.mjs`);
  const targetPath = existsSync(docPathTS) ? docPathTS : existsSync(docPathJS) ? docPathJS : null;

  if (!targetPath) return null;

  const doc = evaluateDocFile(targetPath);
  if (!doc) throw new Error(`${relative(ROOT, targetPath)} must export \`docs\``);

  const description = (doc.description ?? "").trim();
  const bestPractices = (doc.usage?.bestPractices ?? []).map((b) => ({
    guidance: Boolean(b.guidance),
    description: String(b.description).trim(),
  }));
  const examples = (doc.examples ?? []).map((e) => ({ title: String(e.title).trim(), code: String(e.code).trim() }));
  const docsDense = {
    description: compressText(description),
    bestPractices: bestPractices.map((b) => ({ guidance: b.guidance, description: compressText(b.description) })),
  };

  return { description, bestPractices, examples, docsDense };
}

const LAYOUT_COMPONENTS = new Set(["Flex", "Grid", "Container", "Section", "Box", "AppFrame", "Row", "Sidebar", "SidebarHeader", "SidebarBody", "SidebarFooter", "SidebarSection"]);
// Behaviour only (does it lay out children?), not a navigation category:
// grouping comes from each doc file's `group` (docs sidebar structure).
function determineBuilderMeta(name, props) {
  const isLayout = LAYOUT_COMPONENTS.has(name);
  const iconSlots = props.filter((p) => /Icon$|^icon$/.test(p.name)).map((p) => p.name);

  let accepts = ["*"];
  let hasChildren = true;

  if (name === "Tabs") accepts = ["TabsList", "TabsContent"];
  else if (name === "TabsList") accepts = ["TabsTrigger"];
  else if (name === "TabsContent") accepts = ["*"];
  else if (name === "Table") accepts = ["TableHeader", "TableBody", "TableRow"];
  else if (name === "TableHeader") accepts = ["TableRow"];
  else if (name === "TableBody") accepts = ["TableRow"];
  else if (name === "TableRow") accepts = ["TableColumnHeaderCell", "TableCell"];
  else if (name === "Menu") accepts = ["MenuItem", "MenuSub"];
  else if (name === "Sidebar") accepts = ["SidebarHeader", "SidebarBody", "SidebarFooter", "SidebarSection", "SidebarNavItem"];
  else if (["Button", "IconButton", "Badge", "Separator", "Switch", "Checkbox", "Image", "Spinner", "Progress"].includes(name)) {
    hasChildren = ["Button", "Badge"].includes(name);
    if (!hasChildren) accepts = [];
  }

  const label = name.replace(/([A-Z])/g, " $1").trim();

  return {
    label,
    isLayout,
    hasChildren,
    accepts,
    iconSlots,
  };
}

function build() {
  const primDir = existsSync(join(UI_DIR, "src", "primitives")) ? join(UI_DIR, "src", "primitives") : join(ROOT, "src", "primitives");
  const files = walk(primDir).filter(f => f.endsWith(".tsx") && !f.endsWith("index.tsx")).sort();
  const componentMap = new Map();

  // Folder-level facts from each folder's own doc file: `internal: true` marks
  // Shavin tooling (not a primitive); `group` places it in the docs structure
  // (layout | typography | components).
  const internalDirs = new Set();
  const dirGroup = new Map();
  const dirDoc = new Map(); // folder → its doc (attached only to the component it names)
  for (const d of readdirSync(primDir, { withFileTypes: true }).filter((e) => e.isDirectory())) {
    const docPath = join(primDir, d.name, `${d.name}.doc.ts`);
    const doc = existsSync(docPath) ? evaluateDocFile(docPath) : null;
    if (doc?.internal === true) internalDirs.add(d.name);
    dirGroup.set(d.name, doc?.internal ? "internal" : doc?.group ?? "components");
    if (doc) dirDoc.set(d.name, { name: doc.name, ...loadCoLocatedDoc(join(primDir, d.name), d.name) });
  }

  files.forEach((file) => {
    const rawSrc = readFileSync(file, "utf8");
    const src = stripComments(rawSrc);
    const fileDir = dirname(file);
    const primaryName = basename(file, ".tsx");
    const radixMatch = src.match(/from\s+["'](@radix-ui\/react-[\w-]+)["']/);
    const blocks = cvaBlocks(src);
    const exportedSymbols = exportsOf(src).filter((s) => /^[A-Z]/.test(s) && s !== "ALL_ICONS");
    const folderDoc = dirDoc.get(basename(fileDir));

    // The file name is emitted only when it is a real export or the folder's doc
    // is written for it (e.g. Emphasis → Em, Strong, Quote; Toast → ToastProvider).
    const namesToEmit = Array.from(
      new Set([
        ...(exportedSymbols.includes(primaryName) || folderDoc?.name === primaryName ? [primaryName] : []),
        ...exportedSymbols,
      ]),
    );

    const internal = internalDirs.has(basename(fileDir));

    namesToEmit.forEach((name) => {
      const parsedProps = parseProps(rawSrc, name);
      const { variants, defaults } = variantsFor(src, name, blocks, name === primaryName);
      // The folder's doc describes one component; the folder's other exports point to it.
      const doc = folderDoc && folderDoc.name === name ? folderDoc : null;
      const partOf = folderDoc && folderDoc.name !== name ? folderDoc.name : undefined;
      componentMap.set(name, {
        name,
        group: dirGroup.get(basename(fileDir)) ?? "components",
        ...(internal ? { internal: true } : {}),
        docsPath: docsPathFor(basename(fileDir)),
        ...(IMPORT_PATH_BY_FOLDER[basename(fileDir)] ? { importPath: IMPORT_PATH_BY_FOLDER[basename(fileDir)] } : {}),
        file: relative(ROOT, file),
        kind: radixMatch ? "radix" : "plain",
        radix: radixMatch ? radixMatch[1] : null,
        radiusOverride: Object.prototype.hasOwnProperty.call(variants, "radius"),
        variants,
        defaultVariants: defaults,
        props: parsedProps,
        builderMeta: determineBuilderMeta(name, parsedProps),
        exports: exportedSymbols,
        ...(partOf ? { partOf } : {}),
        description: doc?.description || undefined,
        bestPractices: doc?.bestPractices || undefined,
        examples: doc?.examples || undefined,
        docsDense: doc?.docsDense || undefined,
      });
    });
  });

  const components = Array.from(componentMap.values()).sort((a, b) => a.name.localeCompare(b.name));

  // Fallback: components whose props the regex parser could not see (type aliases,
  // inline param types, Radix/forwardRef wrappers) are resolved with the TS compiler.
  const absFiles = files;
  for (const comp of components) {
    // Charts inherit shared axis options (height, yMax, xLabels, ...) from `AxisProps` in chart-kit;
    // the regex parser only sees an interface's own members, so merge the inherited ones in.
    if (comp.props.length && /extends[^{]*\bAxisProps\b/.test(readFileSync(join(ROOT, comp.file), "utf8"))) {
      try {
        const r = tsProps(UI_DIR, absFiles, join(ROOT, comp.file), comp.name);
        const have = new Set(comp.props.map((x) => x.name));
        const AXIS = (r?.props ?? []).filter((x) => !have.has(x.name));
        if (AXIS.length) comp.props = [...comp.props, ...AXIS].sort((a, b) => a.name.localeCompare(b.name));
      } catch (e) {
        console.warn(`ts-props (axis): ${comp.name}: ${e.message}`);
      }
      continue;
    }
    if (comp.props.length) continue;
    try {
      const r = tsProps(UI_DIR, absFiles, join(ROOT, comp.file), comp.name);
      if (r) {
        if (r.props.length) {
          comp.props = r.props;
          comp.builderMeta = determineBuilderMeta(comp.name, r.props);
        }
        if (r.inherits) comp.inheritsDomProps = true;
      }
    } catch (e) {
      console.warn(`ts-props: ${comp.name}: ${e.message}`);
    }
  }
  const primitiveDirs = existsSync(primDir)
    ? readdirSync(primDir, { withFileTypes: true }).filter(d => d.isDirectory())
    : [];

  return {
    generated: "by scripts/gen-manifest.mjs -- do not edit by hand (run: npm run manifest:gen)",
    docs: "AGENTS.md -- 'When to reach for Radix' + shape-override notes carry the when-to-use rationale",
    count: components.length,
    primitiveCount: primitiveDirs.filter((d) => !internalDirs.has(d.name)).length,
    internalCount: primitiveDirs.filter((d) => internalDirs.has(d.name)).length,
    components,
  };
}

function buildMetaTs(primitiveDirCount) {
  let pkgVersion = "0.1.0";
  try {
    const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
    if (pkg.version) pkgVersion = pkg.version;
  } catch {
    /* fallback to 0.1.0 */
  }

  // Skill sources, not the generated .agents/ copy, so the result does not depend
  // on whether skills:build ran first.
  const skillsDir = existsSync(join(ROOT, "packages", "skills", "skills"))
    ? join(ROOT, "packages", "skills", "skills")
    : join(ROOT, ".agents", "skills");
  const skills = [];
  if (existsSync(skillsDir)) {
    const skillEntries = readdirSync(skillsDir, { withFileTypes: true }).filter(d => d.isDirectory()).sort();
    for (const entry of skillEntries) {
      const skillMd = join(skillsDir, entry.name, "SKILL.md");
      let desc = "Agent specialized skill";
      if (existsSync(skillMd)) {
        const raw = readFileSync(skillMd, "utf8");
        const match = raw.match(/^description:\s*(.*)$/m);
        if (match) {
          let text = match[1].trim();
          if (text === ">" || text === "|" || text === ">-" || text === "|-") {
            // YAML block scalar: the indented lines that follow.
            const after = raw.slice(match.index + match[0].length).split("\n").slice(1);
            const lines = [];
            for (const line of after) {
              if (!/^\s+\S/.test(line)) break;
              lines.push(line.trim());
            }
            text = lines.join(" ");
          }
          text = text.replace(/["']/g, "").trim();
          const sentence = text.match(/^.*?[.!?](?=\s|$)/)?.[0] ?? text;
          if (sentence) desc = sentence.length > 160 ? sentence.slice(0, 157).trimEnd() + "..." : sentence;
        }
      }
      skills.push({ name: entry.name, desc });
    }
  }

  const toolsDir = join(ROOT, "packages", "mcp-server", "src", "tools");
  const mcpTools = [];
  if (existsSync(toolsDir)) {
    const toolFiles = readdirSync(toolsDir).filter(f => f.endsWith(".mjs")).sort();
    for (const f of toolFiles) {
      const src = readFileSync(join(toolsDir, f), "utf8");
      const matches = src.matchAll(/name:\s*["']([a-z][a-z0-9]*_[a-z0-9_]+)["']/g); // tool names are snake_case
      for (const m of matches) {
        if (!mcpTools.includes(m[1])) {
          mcpTools.push(m[1]);
        }
      }
    }
  }
  mcpTools.sort();

  // @shavin/ui is public, so its meta counts only the open catalogue
  // (packages/block-schema/blocks/**). Totals that include pro blocks go to the
  // private website stats file below.
  const blockCount = countBlocks(join(ROOT, "packages", "block-schema", "blocks"));

  return `/**
 * @shavin/ui Master Design System Metadata & Statistics
 * AUTO-GENERATED by scripts/gen-manifest.mjs — DO NOT EDIT DIRECTLY.
 * Run \`npm run manifest:gen\` to regenerate.
 */

export const SHAVIN_META = {
  version: ${JSON.stringify(pkgVersion)},
  primitiveCount: ${primitiveDirCount},
  mcpToolCount: ${mcpTools.length},
  skillCount: ${skills.length},
  blockCount: ${blockCount},
  manifestCount: 2,
  tokenPurityTarget: 100,
  mcpTools: [
${mcpTools.map(t => `    "${t}",`).join("\n")}
  ] as const,
  skills: [
${skills.map(s => `    { name: "${s.name}", desc: "${s.desc.replace(/"/g, '\\"')}" },`).join("\n")}
  ] as const,
} as const;

export type ShavinMeta = typeof SHAVIN_META;
export type ShavinMcpTool = (typeof SHAVIN_META.mcpTools)[number];
`;
}

