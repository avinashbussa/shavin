function buildRoutesTs(components) {
  const entries = components.map((c) => `  ${JSON.stringify(c.name)}: ${JSON.stringify(c.docsPath)},`).join("\n");
  return `// Generated by scripts/gen-manifest.mjs -- do not edit by hand (run: npm run manifest:gen).
// Docs page for every exported component. Import from "@shavin/ui/lib/docs-routes".

export const DOCS_BASE_URL = "https://docs.shavin.cc";

export const DOCS_ROUTES: Record<string, string> = {
${entries}
};

/** Docs path for a component name (e.g. "LineChart" -> "/components/charts"). Unknown names go to the overview. */
export function docsPath(name: string): string {
  return DOCS_ROUTES[name] ?? "/components/overview";
}

/** Absolute docs URL for a component name. Pass \`base\` for a local docs server. */
export function docsUrl(name: string, base: string = DOCS_BASE_URL): string {
  return \`\${base}\${docsPath(name)}\`;
}
`;
}

/** docsPath values with no page in apps/docs (private repo only). */
function missingDocsPages(components) {
  if (!DOCS_APP) return [];
  const bad = new Map();
  for (const c of components) {
    if (!existsSync(join(DOCS_APP, c.docsPath, "page.tsx"))) bad.set(c.docsPath, [...(bad.get(c.docsPath) ?? []), c.name]);
  }
  return [...bad].map(([path, names]) => `${path} (${names.join(", ")})`);
}
