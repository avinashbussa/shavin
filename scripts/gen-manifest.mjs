function countBlocks(blocksDir) {
  if (!existsSync(blocksDir)) return 0;
  let n = 0;
  for (const cat of readdirSync(blocksDir, { withFileTypes: true }).filter((d) => d.isDirectory())) {
    n += readdirSync(join(blocksDir, cat.name)).filter((f) => f.endsWith(".tsx")).length;
  }
  return n;
}

